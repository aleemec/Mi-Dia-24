import React, { useEffect, useMemo, useState } from 'react';
import {
  BookmarkPlus,
  CalendarCheck2,
  ChevronLeft,
  ChevronRight,
  Copy,
  Repeat,
  X,
} from 'lucide-react';
import {
  DayRecord,
  DayTemplate,
  formatDateKey,
  formatDisplayDate,
  formatHourLabel,
  getMonthCalendarDays,
  MAX_REPLICATE_DATES,
  MAX_TEMPLATE_NAME_LENGTH,
  MONTHS_ES,
  parseDateKey,
  ReplicationStrategy,
  TemplateSlot,
  TimeFormat,
  WEEKDAYS_SHORT_ES,
} from '../types/planner';

interface SaveReplicateModalProps {
  isOpen: boolean;
  initialTab?: 'save' | 'replicate';
  initialTemplateId?: string | null;
  currentDateKey: string;
  currentRecord?: DayRecord;
  templates: DayTemplate[];
  timeFormat: TimeFormat;
  onClose: () => void;
  onSaveTemplate: (name: string, slots: TemplateSlot[]) => DayTemplate;
  onReplicateToDates: (
    targetDates: string[],
    slots: TemplateSlot[],
    strategy: ReplicationStrategy
  ) => void;
}

type HorizonOption = 'week' | 'month' | 'quarter' | 'year';

export const SaveReplicateModal: React.FC<SaveReplicateModalProps> = ({
  isOpen,
  initialTab = 'save',
  initialTemplateId = null,
  currentDateKey,
  currentRecord,
  templates,
  timeFormat,
  onClose,
  onSaveTemplate,
  onReplicateToDates,
}) => {
  const [activeTab, setActiveTab] = useState<'save' | 'replicate'>(initialTab);
  const [templateName, setTemplateName] = useState('');
  const [sourceId, setSourceId] = useState<string>(
    initialTemplateId ?? 'current-day'
  );
  const [replicateMode, setReplicateMode] = useState<'dates' | 'weekdays'>('dates');
  const [strategy, setStrategy] = useState<ReplicationStrategy>('merge');

  // Multi-date picker state
  const currentParsed = parseDateKey(currentDateKey);
  const [pickerYear, setPickerYear] = useState(currentParsed.getFullYear());
  const [pickerMonth, setPickerMonth] = useState(currentParsed.getMonth());
  const [selectedDates, setSelectedDates] = useState<string[]>([]);

  // Weekday pattern state (0=Mon .. 6=Sun)
  const [selectedWeekdays, setSelectedWeekdays] = useState<number[]>([0, 2, 4]);
  const [horizon, setHorizon] = useState<HorizonOption>('month');

  useEffect(() => {
    if (!isOpen) return;
    const onKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', onKeyDown);
    return () => window.removeEventListener('keydown', onKeyDown);
  }, [isOpen, onClose]);

  // Extract slots from current day
  const currentSlots: TemplateSlot[] = useMemo(() => {
    if (!currentRecord?.tasks) return [];
    return Object.values(currentRecord.tasks)
      .filter((t) => t && typeof t.text === 'string' && t.text.trim().length > 0)
      .sort((a, b) => a.hour - b.hour)
      .map((t) => ({ hour: t.hour, text: t.text.trim() }));
  }, [currentRecord]);

  // Slots chosen for replication
  const activeSlots: TemplateSlot[] = useMemo(() => {
    if (sourceId === 'current-day') return currentSlots;
    const found = templates.find((t) => t.id === sourceId);
    return found ? found.slots : [];
  }, [sourceId, currentSlots, templates]);

  // Compute dates generated by weekday pattern
  const weekdayGeneratedDates: string[] = useMemo(() => {
    if (selectedWeekdays.length === 0) return [];
    const start = parseDateKey(currentDateKey);
    const end = new Date(start.getFullYear(), start.getMonth(), start.getDate());

    if (horizon === 'week') {
      end.setDate(end.getDate() + 7);
    } else if (horizon === 'month') {
      end.setMonth(end.getMonth() + 1);
    } else if (horizon === 'quarter') {
      end.setMonth(end.getMonth() + 3);
    } else {
      end.setFullYear(end.getFullYear() + 1);
    }

    const result: string[] = [];
    const cursor = new Date(start.getFullYear(), start.getMonth(), start.getDate() + 1);
    while (cursor <= end) {
      const mondayIndex = (cursor.getDay() + 6) % 7;
      if (selectedWeekdays.includes(mondayIndex)) {
        result.push(formatDateKey(cursor));
      }
      cursor.setDate(cursor.getDate() + 1);
    }
    return result;
  }, [currentDateKey, selectedWeekdays, horizon]);

  if (!isOpen) return null;

  const pickerCells = getMonthCalendarDays(pickerYear, pickerMonth);
  const dateDisplay = formatDisplayDate(currentDateKey);
  const targetDatesFinal = (
    replicateMode === 'dates' ? selectedDates : weekdayGeneratedDates
  ).slice(0, MAX_REPLICATE_DATES);

  const toggleDateSelection = (dKey: string) => {
    setSelectedDates((prev) =>
      prev.includes(dKey) ? prev.filter((item) => item !== dKey) : [...prev, dKey]
    );
  };

  const toggleWeekday = (wdIdx: number) => {
    setSelectedWeekdays((prev) =>
      prev.includes(wdIdx) ? prev.filter((d) => d !== wdIdx) : [...prev, wdIdx]
    );
  };

  const handleSaveNewTemplate = (e: React.FormEvent) => {
    e.preventDefault();
    if (currentSlots.length === 0) return;
    const finalName = (
      templateName.trim() || `Rutina del ${dateDisplay.shortLabel}`
    ).slice(0, MAX_TEMPLATE_NAME_LENGTH);
    const created = onSaveTemplate(finalName, currentSlots);
    setTemplateName('');
    setSourceId(created.id);
    setActiveTab('replicate');
  };

  const handleConfirmReplicate = () => {
    if (activeSlots.length === 0 || targetDatesFinal.length === 0) return;
    onReplicateToDates(targetDatesFinal, activeSlots, strategy);
    onClose();
  };

  return (
    <div
      onClick={(e) => {
        if (e.target === e.currentTarget) onClose();
      }}
      className="fixed inset-0 z-50 flex items-end sm:items-center justify-center bg-[#223A5E]/35 backdrop-blur-xs p-0 sm:p-4"
      role="dialog"
      aria-modal="true"
      aria-label="Guardar y replicar día"
    >
      <div className="w-full sm:max-w-lg bg-[#FAFBFD] rounded-t-3xl sm:rounded-3xl border border-[#C7DCF2] shadow-2xl overflow-hidden max-h-[90vh] flex flex-col">
        {/* Mobile grab handle */}
        <div className="sm:hidden flex justify-center pt-2.5">
          <div className="w-10 h-1 rounded-full bg-[#C7DCF2]" />
        </div>

        {/* Header */}
        <div className="px-5 py-3.5 border-b border-[#D2E6F9] flex items-center justify-between gap-3">
          <h2 className="font-display text-lg font-semibold text-[#223A5E]">
            Guardar y replicar día
          </h2>
          <button
            type="button"
            onClick={onClose}
            aria-label="Cerrar ventana"
            className="min-w-[44px] min-h-[44px] flex items-center justify-center rounded-xl text-[#5E7A9E] hover:bg-[#E1EEFA] hover:text-[#223A5E] transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Mode Segmented Tabs */}
        <div className="px-5 pt-3">
          <div className="grid grid-cols-2 gap-1 p-1 rounded-xl bg-[#E1EEFA]">
            <button
              type="button"
              onClick={() => setActiveTab('save')}
              className={`min-h-[40px] px-3 py-1.5 rounded-lg text-xs sm:text-sm font-medium flex items-center justify-center gap-1.5 transition-all ${
                activeTab === 'save'
                  ? 'bg-[#FAFBFD] text-[#223A5E] shadow-xs'
                  : 'text-[#5E7A9E] hover:text-[#223A5E]'
              }`}
            >
              <BookmarkPlus className="w-4 h-4" />
              <span>Guardar plantilla</span>
            </button>
            <button
              type="button"
              onClick={() => setActiveTab('replicate')}
              className={`min-h-[40px] px-3 py-1.5 rounded-lg text-xs sm:text-sm font-medium flex items-center justify-center gap-1.5 transition-all ${
                activeTab === 'replicate'
                  ? 'bg-[#FAFBFD] text-[#223A5E] shadow-xs'
                  : 'text-[#5E7A9E] hover:text-[#223A5E]'
              }`}
            >
              <Copy className="w-4 h-4" />
              <span>Copiar a fechas</span>
            </button>
          </div>
        </div>

        {/* Scrollable Content */}
        <div className="p-5 overflow-y-auto paper-scroll flex-1 space-y-4">
          {activeTab === 'save' ? (
            <form onSubmit={handleSaveNewTemplate} className="space-y-4">
              <div>
                <label
                  htmlFor="template-name-input"
                  className="block text-xs font-semibold text-[#223A5E] mb-1.5"
                >
                  Nombre de la plantilla
                </label>
                <input
                  id="template-name-input"
                  type="text"
                  maxLength={MAX_TEMPLATE_NAME_LENGTH}
                  autoComplete="off"
                  value={templateName}
                  onChange={(e) => setTemplateName(e.target.value)}
                  placeholder="Ej. Día de facultad, Rutina gym..."
                  className="w-full min-h-[44px] px-3.5 py-2.5 rounded-xl border border-[#C7DCF2] bg-white text-sm text-[#223A5E] placeholder:text-[#9BB5D4] focus:outline-none focus:border-[#568FD1]"
                />
              </div>

              <div className="rounded-2xl bg-[#F4F8FC] border border-[#D7E6F6] p-3.5">
                <p className="text-xs font-medium text-[#5E7A9E] mb-2">
                  Resumen de {dateDisplay.shortLabel} · {currentSlots.length} horas
                  con tareas
                </p>
                {currentSlots.length === 0 ? (
                  <p className="text-sm text-[#5E7A9E]">
                    Este día aún no tiene tareas escritas. Anota al menos una hora
                    en tu hoja para poder guardarla como plantilla.
                  </p>
                ) : (
                  <ul className="space-y-1 max-h-40 overflow-y-auto paper-scroll pr-1">
                    {currentSlots.map((slot) => (
                      <li
                        key={slot.hour}
                        className="flex items-baseline gap-2.5 text-sm text-[#223A5E]"
                      >
                        <span className="font-mono tabular-nums text-xs text-[#5E7A9E] w-11 shrink-0">
                          {formatHourLabel(slot.hour, timeFormat)}
                        </span>
                        <span className="truncate">{slot.text}</span>
                      </li>
                    ))}
                  </ul>
                )}
              </div>

              <button
                type="submit"
                disabled={currentSlots.length === 0}
                className="w-full min-h-[46px] px-4 py-2.5 rounded-xl bg-[#568FD1] hover:bg-[#4279BA] disabled:bg-[#C7DCF2] disabled:cursor-not-allowed text-white text-sm font-semibold transition-colors"
              >
                Guardar plantilla y elegir fechas
              </button>
            </form>
          ) : (
            <div className="space-y-4">
              {/* Source Routine Selector */}
              <div>
                <label
                  htmlFor="replicate-source-select"
                  className="block text-xs font-semibold text-[#223A5E] mb-1.5"
                >
                  Qué tareas quieres replicar
                </label>
                <select
                  id="replicate-source-select"
                  value={sourceId}
                  onChange={(e) => setSourceId(e.target.value)}
                  className="w-full min-h-[44px] px-3.5 py-2 rounded-xl border border-[#C7DCF2] bg-white text-sm text-[#223A5E] focus:outline-none focus:border-[#568FD1]"
                >
                  <option value="current-day">
                    Hoja actual ({dateDisplay.shortLabel} · {currentSlots.length} tareas)
                  </option>
                  {templates.map((tpl) => (
                    <option key={tpl.id} value={tpl.id}>
                      Plantilla: {tpl.name} ({tpl.slots.length} tareas)
                    </option>
                  ))}
                </select>
              </div>

              {activeSlots.length === 0 ? (
                <p className="text-sm text-[#5E7A9E] bg-[#F4F8FC] border border-[#D7E6F6] rounded-2xl p-3.5">
                  La fuente seleccionada no tiene tareas todavía. Escribe tareas en
                  tu día o selecciona una plantilla guardada.
                </p>
              ) : (
                <>
                  {/* Mode: Specific dates vs Weekday recurrence */}
                  <div className="flex items-center gap-2">
                    <button
                      type="button"
                      onClick={() => setReplicateMode('dates')}
                      className={`flex-1 min-h-[40px] px-3 py-1.5 rounded-xl border text-xs font-medium flex items-center justify-center gap-1.5 transition-colors ${
                        replicateMode === 'dates'
                          ? 'border-[#568FD1] bg-[#E1EEFA] text-[#223A5E]'
                          : 'border-[#D7E6F6] bg-white text-[#5E7A9E]'
                      }`}
                    >
                      <CalendarCheck2 className="w-4 h-4" />
                      <span>Elegir fechas</span>
                    </button>
                    <button
                      type="button"
                      onClick={() => setReplicateMode('weekdays')}
                      className={`flex-1 min-h-[40px] px-3 py-1.5 rounded-xl border text-xs font-medium flex items-center justify-center gap-1.5 transition-colors ${
                        replicateMode === 'weekdays'
                          ? 'border-[#568FD1] bg-[#E1EEFA] text-[#223A5E]'
                          : 'border-[#D7E6F6] bg-white text-[#5E7A9E]'
                      }`}
                    >
                      <Repeat className="w-4 h-4" />
                      <span>Repetir por días</span>
                    </button>
                  </div>

                  {replicateMode === 'dates' ? (
                    <div className="rounded-2xl border border-[#D7E6F6] bg-white p-3">
                      <div className="flex items-center justify-between mb-2">
                        <button
                          type="button"
                          onClick={() => {
                            if (pickerMonth === 0) {
                              setPickerMonth(11);
                              setPickerYear((y) => y - 1);
                            } else {
                              setPickerMonth((m) => m - 1);
                            }
                          }}
                          className="min-w-[36px] min-h-[36px] flex items-center justify-center rounded-lg hover:bg-[#E1EEFA] text-[#223A5E]"
                          aria-label="Mes anterior"
                        >
                          <ChevronLeft className="w-4 h-4" />
                        </button>
                        <span className="text-xs font-semibold text-[#223A5E]">
                          {MONTHS_ES[pickerMonth]} {pickerYear}
                        </span>
                        <button
                          type="button"
                          onClick={() => {
                            if (pickerMonth === 11) {
                              setPickerMonth(0);
                              setPickerYear((y) => y + 1);
                            } else {
                              setPickerMonth((m) => m + 1);
                            }
                          }}
                          className="min-w-[36px] min-h-[36px] flex items-center justify-center rounded-lg hover:bg-[#E1EEFA] text-[#223A5E]"
                          aria-label="Mes siguiente"
                        >
                          <ChevronRight className="w-4 h-4" />
                        </button>
                      </div>

                      <div className="grid grid-cols-7 gap-1 mb-1">
                        {WEEKDAYS_SHORT_ES.map((w) => (
                          <div
                            key={w}
                            className="text-center text-[10px] font-semibold text-[#5E7A9E]"
                          >
                            {w}
                          </div>
                        ))}
                      </div>

                      <div className="grid grid-cols-7 gap-1">
                        {pickerCells.map((cell) => {
                          const isPicked = selectedDates.includes(cell.dateKey);
                          return (
                            <button
                              key={cell.dateKey}
                              type="button"
                              onClick={() => toggleDateSelection(cell.dateKey)}
                              className={`h-9 rounded-lg font-mono tabular-nums text-xs transition-colors ${
                                isPicked
                                  ? 'bg-[#568FD1] text-white font-semibold'
                                  : cell.isCurrentMonth
                                  ? 'text-[#223A5E] hover:bg-[#E1EEFA]'
                                  : 'text-[#A9C1DE] hover:bg-[#F4F8FC]'
                              }`}
                            >
                              {cell.dayNumber}
                            </button>
                          );
                        })}
                      </div>
                    </div>
                  ) : (
                    <div className="rounded-2xl border border-[#D7E6F6] bg-white p-3.5 space-y-3">
                      <div>
                        <p className="text-xs font-medium text-[#5E7A9E] mb-2">
                          Días de la semana
                        </p>
                        <div className="grid grid-cols-7 gap-1.5">
                          {WEEKDAYS_SHORT_ES.map((label, idx) => {
                            const active = selectedWeekdays.includes(idx);
                            return (
                              <button
                                key={label}
                                type="button"
                                onClick={() => toggleWeekday(idx)}
                                className={`min-h-[40px] rounded-lg text-xs font-semibold transition-colors ${
                                  active
                                    ? 'bg-[#568FD1] text-white'
                                    : 'bg-[#F4F8FC] text-[#5E7A9E] hover:bg-[#E1EEFA]'
                                }`}
                              >
                                {label.slice(0, 2)}
                              </button>
                            );
                          })}
                        </div>
                      </div>

                      <div>
                        <p className="text-xs font-medium text-[#5E7A9E] mb-1.5">
                          Durante cuánto tiempo
                        </p>
                        <div className="grid grid-cols-2 gap-1.5">
                          {(
                            [
                              ['week', 'Próximos 7 días'],
                              ['month', 'Próximo mes'],
                              ['quarter', 'Próximos 3 meses'],
                              ['year', 'Todo el año'],
                            ] as Array<[HorizonOption, string]>
                          ).map(([opt, text]) => (
                            <button
                              key={opt}
                              type="button"
                              onClick={() => setHorizon(opt)}
                              className={`min-h-[38px] px-2.5 py-1.5 rounded-lg text-xs font-medium border transition-colors ${
                                horizon === opt
                                  ? 'border-[#568FD1] bg-[#E1EEFA] text-[#223A5E]'
                                  : 'border-[#E1EEFA] bg-[#FAFBFD] text-[#5E7A9E]'
                              }`}
                            >
                              {text}
                            </button>
                          ))}
                        </div>
                      </div>
                    </div>
                  )}

                  {/* Merge vs Replace */}
                  <div className="flex items-center justify-between gap-2 text-xs">
                    <span className="text-[#5E7A9E] font-medium">
                      Si el día ya tiene tareas:
                    </span>
                    <div className="flex items-center gap-1 bg-[#E1EEFA] p-0.5 rounded-lg">
                      <button
                        type="button"
                        onClick={() => setStrategy('merge')}
                        className={`px-2.5 py-1.5 rounded-md font-medium transition-colors ${
                          strategy === 'merge'
                            ? 'bg-white text-[#223A5E]'
                            : 'text-[#5E7A9E]'
                        }`}
                      >
                        Combinar
                      </button>
                      <button
                        type="button"
                        onClick={() => setStrategy('replace')}
                        className={`px-2.5 py-1.5 rounded-md font-medium transition-colors ${
                          strategy === 'replace'
                            ? 'bg-white text-[#223A5E]'
                            : 'text-[#5E7A9E]'
                        }`}
                      >
                        Reemplazar
                      </button>
                    </div>
                  </div>
                </>
              )}
            </div>
          )}
        </div>

        {/* Bottom Confirm Bar for Replicate Tab */}
        {activeTab === 'replicate' && activeSlots.length > 0 && (
          <div className="px-5 py-3.5 border-t border-[#D2E6F9] bg-[#F4F8FC] flex items-center justify-between gap-3">
            <span className="text-xs font-mono tabular-nums text-[#5E7A9E]">
              {targetDatesFinal.length} fechas elegidas
            </span>
            <button
              type="button"
              onClick={handleConfirmReplicate}
              disabled={targetDatesFinal.length === 0}
              className="min-h-[44px] px-5 py-2 rounded-xl bg-[#568FD1] hover:bg-[#4279BA] disabled:bg-[#C7DCF2] disabled:cursor-not-allowed text-white text-sm font-semibold transition-colors whitespace-nowrap"
            >
              Aplicar a {targetDatesFinal.length}{' '}
              {targetDatesFinal.length === 1 ? 'fecha' : 'fechas'}
            </button>
          </div>
        )}
      </div>
    </div>
  );
};
